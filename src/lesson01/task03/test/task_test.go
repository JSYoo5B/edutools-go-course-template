package test

import (
	"reflect"
	"testing"

	task "lesson01_task03" // module name = lessonNN_taskMM (generated by build.py from the task directory names)
)

func TestWordCount(t *testing.T) {
	cases := []struct {
		name string
		in   string
		want map[string]int
	}{
		{"empty input", "", map[string]int{}},
		{"ignores case", "Go go GO", map[string]int{"go": 3}},
		{"repeated spaces", "a  b   a", map[string]int{"a": 2, "b": 1}},
	}
	for _, c := range cases {
		got := task.WordCount(c.in)
		if got == nil {
			// In the learner state (not implemented yet) fail right here -> fast feedback.
			t.Fatalf("%s: WordCount returned nil. Return a map created with make", c.name)
		}
		if !reflect.DeepEqual(got, c.want) {
			t.Errorf("%s: WordCount(%q) = %v, want %v", c.name, c.in, got, c.want)
		}
	}
}
